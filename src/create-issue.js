const { Octokit } = require('@octokit/rest');
const fs = require('fs').promises;
const path = require('path');

const REPORT_FILE = path.join(__dirname, '..', 'data', 'new-bounties.json');

async function createIssue() {
  try {
    // Check if there are new bounties
    let report;
    try {
      const data = await fs.readFile(REPORT_FILE, 'utf8');
      report = JSON.parse(data);
    } catch (error) {
      console.log('No new bounties report found');
      return;
    }

    if (!report.bounties || report.bounties.length === 0) {
      console.log('No new bounties to report');
      return;
    }

    const token = process.env.GITHUB_TOKEN;
    if (!token) {
      console.error('GITHUB_TOKEN not found');
      return;
    }

    const octokit = new Octokit({ auth: token });

    // Get repository info from environment or git config
    const repo = process.env.GITHUB_REPOSITORY || 'dev-kp-eloper/BountyScout';
    const [owner, repoName] = repo.split('/');

    // Create issue body
    const issueBody = generateIssueBody(report);
    const issueTitle = `🎯 Bounty Alert: ${report.count} New ${report.count === 1 ? 'Opportunity' : 'Opportunities'} Found`;

    // Create the issue
    const { data: issue } = await octokit.issues.create({
      owner,
      repo: repoName,
      title: issueTitle,
      body: issueBody,
      labels: ['bounty', 'automated', 'new-opportunities']
    });

    console.log(`✅ Issue created: ${issue.html_url}`);

    // Clean up the report file
    await fs.unlink(REPORT_FILE);
  } catch (error) {
    console.error('Error creating issue:', error.message);
    if (error.response) {
      console.error('Response:', error.response.data);
    }
  }
}

function generateIssueBody(report) {
  const { count, bounties, timestamp } = report;
  
  let body = `## 🎯 New Bounty Opportunities Discovered\n\n`;
  body += `**Total Found:** ${count}\n`;
  body += `**Discovered At:** ${new Date(timestamp).toLocaleString()}\n\n`;
  body += `---\n\n`;

  // Group by platform
  const byPlatform = {};
  bounties.forEach(bounty => {
    if (!byPlatform[bounty.platform]) {
      byPlatform[bounty.platform] = [];
    }
    byPlatform[bounty.platform].push(bounty);
  });

  // Generate platform sections
  Object.keys(byPlatform).forEach(platform => {
    body += `### ${platform} (${byPlatform[platform].length})\n\n`;
    
    byPlatform[platform].forEach((bounty, index) => {
      body += `#### ${index + 1}. ${bounty.title}\n\n`;
      body += `- **Reward:** ${bounty.reward}\n`;
      body += `- **Severity:** ${bounty.severity}\n`;
      body += `- **URL:** [View Program](${bounty.url})\n`;
      body += `- **Discovered:** ${new Date(bounty.discoveredAt).toLocaleString()}\n\n`;
    });
  });

  body += `---\n\n`;
  body += `### 📊 Summary by Platform\n\n`;
  Object.keys(byPlatform).forEach(platform => {
    body += `- **${platform}:** ${byPlatform[platform].length} opportunities\n`;
  });

  body += `\n---\n\n`;
  body += `*This issue was automatically generated by BountyScout 🤖*\n`;
  body += `*Last scan: ${new Date(timestamp).toLocaleString()}*`;

  return body;
}

if (require.main === module) {
  createIssue();
}

module.exports = createIssue;