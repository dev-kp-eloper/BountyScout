const { Octokit } = require('@octokit/rest');
const fs = require('fs').promises;
const path = require('path');

const NEW_BOUNTIES_FILE = path.join(__dirname, '..', 'data', 'new-bounties.json');

class IssueCreator {
  constructor() {
    this.octokit = new Octokit({
      auth: process.env.GITHUB_TOKEN
    });
    this.owner = process.env.GITHUB_REPOSITORY?.split('/')[0] || 'dev-kp-eloper';
    this.repo = process.env.GITHUB_REPOSITORY?.split('/')[1] || 'BountyScout';
  }

  async loadNewBounties() {
    try {
      const data = await fs.readFile(NEW_BOUNTIES_FILE, 'utf8');
      return JSON.parse(data);
    } catch (error) {
      if (error.code === 'ENOENT') {
        console.log('No new bounties file found');
        return [];
      }
      throw error;
    }
  }

  formatBountyList(bounties) {
    if (bounties.length === 0) {
      return 'No new bounties found.';
    }

    let markdown = '## 🎯 New Bug Bounty Opportunities\n\n';
    markdown += `Found **${bounties.length}** new ${bounties.length === 1 ? 'opportunity' : 'opportunities'}!\n\n`;

    // Group by platform
    const byPlatform = {};
    for (const bounty of bounties) {
      if (!byPlatform[bounty.platform]) {
        byPlatform[bounty.platform] = [];
      }
      byPlatform[bounty.platform].push(bounty);
    }

    for (const [platform, platformBounties] of Object.entries(byPlatform)) {
      markdown += `### ${platform} (${platformBounties.length})\n\n`;
      
      for (const bounty of platformBounties) {
        markdown += `#### ${bounty.title}\n`;
        markdown += `- **Company:** ${bounty.company}\n`;
        markdown += `- **Bounty Range:** $${bounty.minBounty} - $${bounty.maxBounty}\n`;
        markdown += `- **Scope:** ${bounty.scope}\n`;
        markdown += `- **Status:** ${bounty.status}\n`;
        markdown += `- **URL:** [View Program](${bounty.url})\n`;
        markdown += `- **Discovered:** ${new Date(bounty.discoveredAt).toLocaleString()}\n\n`;
      }
    }

    markdown += '---\n\n';
    markdown += '💡 **Tip:** Click on the program links to learn more and start hunting!\n\n';
    markdown += '🤖 *This issue was automatically generated by BountyScout*';

    return markdown;
  }

  async createIssue(bounties) {
    if (bounties.length === 0) {
      console.log('No new bounties to report');
      return;
    }

    const title = `🎯 Bounty Alert: ${bounties.length} New ${bounties.length === 1 ? 'Opportunity' : 'Opportunities'} Found`;
    const body = this.formatBountyList(bounties);

    try {
      const response = await this.octokit.issues.create({
        owner: this.owner,
        repo: this.repo,
        title: title,
        body: body,
        labels: ['bounty-alert', 'automated']
      });

      console.log(`Created issue #${response.data.number}: ${title}`);
      console.log(`Issue URL: ${response.data.html_url}`);
    } catch (error) {
      console.error('Error creating issue:', error.message);
      throw error;
    }
  }

  async run() {
    try {
      console.log('Loading new bounties...');
      const bounties = await this.loadNewBounties();
      
      console.log(`Found ${bounties.length} new bounties to report`);
      
      if (bounties.length > 0) {
        await this.createIssue(bounties);
      } else {
        console.log('No issue created - no new bounties found');
      }
    } catch (error) {
      console.error('Error in issue creator:', error);
      process.exit(1);
    }
  }
}

if (require.main === module) {
  const creator = new IssueCreator();
  creator.run();
}

module.exports = IssueCreator;