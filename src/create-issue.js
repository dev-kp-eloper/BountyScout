const { Octokit } = require('@octokit/rest');
const fs = require('fs').promises;
const path = require('path');
require('dotenv').config();

const octokit = new Octokit({
  auth: process.env.GITHUB_TOKEN
});

async function createIssueForNewBounties() {
  try {
    const newBountiesFile = path.join(__dirname, '..', 'data', 'new-bounties.json');
    
    let newBounties = [];
    try {
      const data = await fs.readFile(newBountiesFile, 'utf8');
      newBounties = JSON.parse(data);
    } catch (error) {
      if (error.code === 'ENOENT') {
        console.log('No new bounties found.');
        return;
      }
      throw error;
    }

    if (newBounties.length === 0) {
      console.log('No new bounties to report.');
      return;
    }

    // Get repository info from environment or git config
    const repo = process.env.GITHUB_REPOSITORY || 'dev-kp-eloper/BountyScout';
    const [owner, repoName] = repo.split('/');

    // Create issue body
    let issueBody = `## 🎯 New Bounty Opportunities\n\n`;
    issueBody += `Found **${newBounties.length}** new bounty ${newBounties.length === 1 ? 'opportunity' : 'opportunities'}!\n\n`;
    issueBody += `---\n\n`;

    newBounties.forEach((bounty, index) => {
      issueBody += `### ${index + 1}. ${bounty.title}\n\n`;
      issueBody += `- **Source:** ${bounty.source}\n`;
      issueBody += `- **URL:** ${bounty.url}\n`;
      if (bounty.repository) {
        issueBody += `- **Repository:** ${bounty.repository}\n`;
      }
      if (bounty.labels && bounty.labels.length > 0) {
        issueBody += `- **Labels:** ${bounty.labels.join(', ')}\n`;
      }
      if (bounty.description) {
        issueBody += `- **Description:** ${bounty.description}\n`;
      }
      issueBody += `\n`;
    });

    issueBody += `---\n\n`;
    issueBody += `*This issue was automatically generated by BountyScout on ${new Date().toISOString()}*\n`;

    // Fix typo in title: "Opportunityies" -> "Opportunities"
    const issueTitle = `🎯 Bounty Alert: ${newBounties.length} New ${newBounties.length === 1 ? 'Opportunity' : 'Opportunities'} Found`;

    console.log(`Creating issue: ${issueTitle}`);

    const issue = await octokit.issues.create({
      owner,
      repo: repoName,
      title: issueTitle,
      body: issueBody,
      labels: ['bounty-alert', 'automated']
    });

    console.log(`✅ Issue created: ${issue.data.html_url}`);

    // Clean up the new bounties file
    await fs.unlink(newBountiesFile);
    console.log('Cleaned up new bounties file');

  } catch (error) {
    console.error('Error creating issue:', error.message);
    if (error.response) {
      console.error('Response data:', error.response.data);
    }
    process.exit(1);
  }
}

if (require.main === module) {
  createIssueForNewBounties();
}

module.exports = createIssueForNewBounties;